defmodule Mix.Tasks.Baguette.Styles do
  @shortdoc "Generates style classes from GPUI's Styled trait"
  @moduledoc """
  Generates `native/baguette_host/src/style_gen.rs`: one class per method
  of GPUI's `Styled` trait that takes no argument (`w_1_2` is `w-1/2`,
  `mt_neg_2` is `-mt-2`, `p_0p5` is `p-0.5`), limited to the stable
  categories: flex, grid, size, spacing, position, overflow, border,
  radius, shadow, cursor and text.

      mix baguette.styles

  It reads the trait from rustdoc's JSON for `gpui-pre`, which needs a
  nightly toolchain (`rustup toolchain install nightly --profile minimal`).
  Run it when GPUI is bumped and commit the result; builds use the
  committed file.
  """
  use Mix.Task

  # The first word of a method's name, for each stable category.
  @stable ~w(
    flex items justify content self
    grid col row
    w h size min max aspect
    p pt pb pl pr px py m mt mb ml mr mx my gap
    relative absolute inset top bottom left right
    overflow border rounded shadow cursor
    text whitespace truncate italic not underline line
  )

  @impl true
  def run(_args) do
    native = Path.join(Mix.Project.deps_paths()[:baguette] || File.cwd!(), "native")
    target = Path.join(System.tmp_dir!(), "baguette-rustdoc")

    Mix.shell().info([:green, "* rustdoc ", :reset, "gpui-pre (nightly)"])

    {_, 0} =
      System.cmd(
        "cargo",
        ~w(+nightly rustdoc -q -p gpui-pre --lib --target-dir) ++
          [target, "--", "-Z", "unstable-options", "--output-format", "json"],
        cd: native,
        into: IO.stream()
      )

    rustdoc = target |> Path.join("doc/gpui.json") |> File.read!() |> JSON.decode!()
    version = rustdoc["crate_version"] || "unknown"
    out = Path.join(native, "baguette_host/src/style_gen.rs")
    File.write!(out, render(methods(rustdoc), version))
    Mix.shell().info([:green, "* wrote ", :reset, Path.relative_to_cwd(out)])
  end

  @doc "The names of `Styled`'s argument-free methods in the stable categories, sorted."
  @spec methods(map()) :: [String.t()]
  def methods(%{"index" => index}) do
    [styled] = for {_, %{"name" => "Styled", "inner" => %{"trait" => t}}} <- index, do: t

    for id <- styled["items"],
        %{"name" => name, "inner" => %{"function" => %{"sig" => sig}}} <- [index["#{id}"]],
        match?([["self", _]], sig["inputs"]),
        sig["output"] == %{"generic" => "Self"},
        hd(String.split(name, "_")) in @stable do
      name
    end
    |> Enum.sort()
  end

  @doc "The class a method stands for, as Tailwind names it."
  @spec class_name(String.t()) :: String.t()
  def class_name(method) do
    {negative, words} =
      case String.split(method, "_") do
        [prop, "neg" | rest] -> {true, [prop | rest]}
        [a, b, "neg" | rest] -> {true, [a, b | rest]}
        words -> {false, words}
      end

    words =
      case Enum.reverse(words) do
        [d, n, prev | rest] when prev != "" ->
          if digits?(n) and digits?(d) and not digits?(prev),
            do: Enum.reverse([n <> "/" <> d, prev | rest]),
            else: words

        _ ->
          words
      end

    name = words |> Enum.map(&String.replace(&1, ~r/^(\d+)p(\d+)$/, "\\1.\\2")) |> Enum.join("-")
    if negative, do: "-" <> name, else: name
  end

  defp digits?(word), do: word =~ ~r/^\d+$/

  @doc "The generated Rust source for `methods`: a table sorted by class."
  @spec render([String.t()], String.t()) :: String.t()
  def render(methods, version) do
    classes = methods |> Enum.map(&{class_name(&1), &1}) |> Enum.sort()

    case classes
         |> Enum.map(&elem(&1, 0))
         |> Enum.frequencies()
         |> Enum.filter(&(elem(&1, 1) > 1)) do
      [] -> :ok
      dups -> Mix.raise("methods share a class name: #{inspect(dups)}")
    end

    rows =
      Enum.map_join(classes, "\n", fn {class, method} ->
        ~s[    ("#{class}", |r| r.#{method}()),]
      end)

    """
    // @generated by `mix baguette.styles` from gpui-pre #{version}'s rustdoc. Do not edit.
    //
    // One class per argument-free method of GPUI's `Styled` trait in the
    // stable categories (docs/native-api.md), for the classes `style.rs`
    // doesn't handle itself.

    use tauri_plugin_gpui::gpui::{StyleRefinement, Styled};

    struct Refinement(StyleRefinement);

    impl Styled for Refinement {
        fn style(&mut self) -> &mut StyleRefinement {
            &mut self.0
        }
    }

    /// What `class` sets, if it names one of the methods.
    pub fn refinement(class: &str) -> Option<StyleRefinement> {
        let at = CLASSES
            .binary_search_by(|(name, _)| name.cmp(&class))
            .ok()?;
        Some((CLASSES[at].1)(Refinement(StyleRefinement::default())).0)
    }

    type Method = fn(Refinement) -> Refinement;

    /// Sorted by class, for `refinement`'s binary search.
    #[rustfmt::skip]
    static CLASSES: &[(&str, Method)] = &[
    #{rows}
    ];
    """
  end
end
